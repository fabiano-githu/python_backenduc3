'''

2. Função que retorna o maior de dois números
Crie uma função maior(a, b) que devolve qual número é maior usando if/else.



	
'''


print("\n----------Função que retorna o maior de dois números------------------\n")

def maior(a, b):
    if a > b:
        return a
    else:
        return b

print(maior(10, 5))

print("\n------------------------------------------------------------------------\n")
