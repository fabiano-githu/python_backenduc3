'''
10. Função que retorna uma tabuada Exemplo: tabuada(7)
 Use for para imprimir de 1 a 10.
	
'''


print("\n---10. Função que retorna uma tabuada Exemplo: tabuada(7)---\n")


def tabuada(numero):
    for i in range(1, 11):
        print(numero, "x", i, "=", numero * i)

tabuada(7)



print("\n------------------------------------------------------------------------\n")
